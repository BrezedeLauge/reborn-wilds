#!/usr/bin/env python3
"""Rebuild the selected, attributed model adapters from checked-in source snapshots.

No network, game decompilation or loader dependency is required. The authoritative
selection and action timing live in design/reference-models.json. Geometry and
AnimationDefinition expressions are retained from their individually documented
upstream sources; gameplay code is deliberately outside this importer.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = 'de.laugenbreze.dungeonsalive.client.entity.reference.imported'
OUT = ROOT / 'src/main/java' / PACKAGE.replace('.', '/')


def block(source: str, start: int) -> str:
    """Extract a balanced Java block; selected generated sources have no brace literals."""
    first = source.index('{', start)
    depth = 1
    i = first + 1
    while depth and i < len(source):
        depth += (source[i] == '{') - (source[i] == '}')
        i += 1
    if depth:
        raise ValueError('Unterminated source method')
    return source[start:i]


def notice(source: dict, path: str) -> str:
    return (f'/* Adapted from {source["name"]}; {source["copyright"]}.\n'
            f' * License: {source["license"]}; see {source["license_path"]}.\n'
            f' * Source revision: {source["commit"]}\n'
            f' * Upstream file: {path}\n'
            ' * Generated by tools/import_reference_models.py; edit the source snapshot or manifest.\n */\n')


def constants(text: str) -> list[str]:
    result = []
    for match in re.finditer(r'(?:public|private|protected) static final AnimationDefinition \w+\s*=', text):
        end = text.index(';', match.start()) + 1
        declaration = text[match.start():end]
        declaration = re.sub(r'^(private|protected)', 'public', declaration)
        result.append(declaration)
    return result


def omit_declared_unbound_channels(text: str, bones: list[str]) -> str:
    """Match upstream's explicitly documented no-op channels for absent legacy bones."""
    for bone in bones:
        pattern = re.compile(r'\.addAnimation\(\s*"' + re.escape(bone) + r'"\s*,')
        while (match := pattern.search(text)) is not None:
            first = text.index('(', match.start())
            depth, i = 1, first + 1
            while depth:
                depth += (text[i] == '(') - (text[i] == ')')
                i += 1
            text = text[:match.start()] + text[i:]
    return text


def quoted(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def number(value: float) -> str:
    s = format(float(value), '.7g')
    if '.' not in s and 'e' not in s.lower():
        s += '.0'
    return s + 'F'


def write_java(name: str, text: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / (name + '.java')).write_text(text, encoding='utf-8')


def main() -> None:
    manifest = json.loads((ROOT / 'design/reference-models.json').read_text())
    imported = {}
    generated = []
    for asset in manifest['assets']:
        if asset.get('external_generator'):
            # CEM/Bedrock converters retain their own complete rig/UV/source audit.
            if not (OUT / (asset['geometry_class'] + '.java')).is_file():
                raise ValueError('Run ' + asset['external_generator'] + ' first')
            continue
        source = manifest['sources'][asset['source']]
        snapshot = ROOT / asset['model_snapshot']
        text = snapshot.read_text()
        expected = asset['model_sha256']
        if hashlib.sha256(snapshot.read_bytes()).hexdigest() != expected:
            raise ValueError(f'Changed source snapshot without updating provenance: {snapshot}')
        name = asset['geometry_class']
        method_name = asset.get('method', 'createBodyLayer')
        match = re.search(r'public static LayerDefinition ' + re.escape(method_name) + r'\([^)]*\)', text)
        if not match:
            raise ValueError(f'Missing geometry factory: {snapshot}')
        geometry = block(text, match.start())
        for old, new in asset.get('symbol_replacements', {}).items():
            geometry = geometry.replace(old, new)
        extras = []
        for helper in asset.get('helper_methods', []):
            hp = ROOT / helper['snapshot']
            hs = hp.read_text()
            hm = re.search(r'public static MeshDefinition ' + re.escape(helper['name']) + r'\([^)]*\)', hs)
            if not hm:
                raise ValueError(f'Missing helper factory: {hp}')
            extras.append(block(hs, hm.start()))
        body = notice(source, asset['upstream_model_path']) + f'package {PACKAGE};\n\n'
        body += ('import net.minecraft.client.model.*;\n'
                 'import net.minecraft.client.model.geom.*;\n'
                 'import net.minecraft.client.model.geom.builders.*;\n'
                 'import net.minecraft.util.Mth;\n\n')
        body += f'public final class {name} {{\n    private {name}() {{}}\n'
        body += geometry + '\n' + '\n'.join(extras) + '\n}\n'
        write_java(name, body)
        generated.append(name)
        for animation in asset.get('animation_sources', []):
            output_class = animation['class']
            if output_class in imported:
                continue
            animation_snapshot = ROOT / animation['snapshot']
            if hashlib.sha256(animation_snapshot.read_bytes()).hexdigest() != animation['sha256']:
                raise ValueError(f'Animation snapshot hash mismatch: {animation_snapshot}')
            clips = constants(animation_snapshot.read_text())
            if not clips:
                raise ValueError(f'No AnimationDefinition constants: {animation_snapshot}')
            animation_text = notice(source, animation['upstream_path']) + f'package {PACKAGE};\n\n'
            animation_text += 'import net.minecraft.client.animation.*;\n\n'
            animation_text += f'public final class {output_class} {{\n    private {output_class}() {{}}\n'
            animation_text += '\n\n'.join(omit_declared_unbound_channels(c, asset.get('discard_unbound_channels', [])) for c in clips) + '\n}\n'
            write_java(output_class, animation_text)
            imported[output_class] = re.findall(r'AnimationDefinition (\w+)\s*=', animation_text)
        for clipname, class_name in asset.get('clip_owners', {}).items():
            if class_name in imported and clipname not in imported[class_name]:
                raise ValueError(f'Unknown clip {class_name}.{clipname}')

    index = ('/* Generated bindings; per-file licenses and hashes: design/reference-models.json. */\n'
             f'package {PACKAGE};\n\n'
             'import java.util.LinkedHashMap;\nimport java.util.Map;\n'
             'import de.laugenbreze.dungeonsalive.client.entity.reference.ReferenceMobDefinition;\n'
             'import de.laugenbreze.dungeonsalive.entity.AttackKind;\n\n'
             'public final class ReferenceModelIndex {\n'
             '    private ReferenceModelIndex() {}\n'
             '    public static Map<String, ReferenceMobDefinition> create() {\n'
             '        var models = new LinkedHashMap<String, ReferenceMobDefinition>();\n')
    assets = {a['key']: a for a in manifest['assets']}
    for model in manifest['models']:
        ident = model['id']
        asset = assets[model['asset']]
        configure = asset.get('configure')
        builder = f'ReferenceMobDefinition.builder({quoted(ident)}, {asset["geometry_class"]}::{asset.get("method", "createBodyLayer")}, {quoted(model["texture"])})'
        if configure:
            builder = asset['geometry_class'] + '.' + configure + '(' + builder + ')'
        index += f'        models.put({quoted(ident)}, {builder}\n'
        if asset.get('baked_root'):
            index += f'            .bakedRoot({asset["geometry_class"]}::bakeRoot)\n'
        index += f'            .scale({number(model.get("scale", 1))})\n'
        clip_owners = asset.get('clip_owners', {}) | model.get('additional_clip_owners', {})
        for clip, owner in clip_owners.items():
            index += f'            .clip({quoted(clip)}, {owner}.{clip})\n'
        if model.get('idle'):
            index += f'            .idle({quoted(model["idle"])})\n'
        if model.get('walk'):
            walk = model['walk']
            index += f'            .walk({quoted(walk["clip"])}, {number(walk["speed"])}, {number(walk["amplitude"])})\n'
        if model.get('swim'):
            swim = model['swim']
            index += f'            .swim({quoted(swim["idle"])}, {quoted(swim["move"])}, {number(swim["speed"])}, {number(swim["amplitude"])})\n'
        for base in model.get('base_clips', []):
            index += f'            .base({quoted(base)})\n'
        for action, binding in model.get('actions', {}).items():
            index += f'            .action(AttackKind.{action}, {quoted(binding["clip"])}, {number(binding["hit_seconds"])})\n'
        if model.get('death'):
            index += f'            .death({quoted(model["death"])})\n'
        if model.get('look'):
            look = model['look']
            index += f'            .look({quoted(look["bone"])}, {number(look["yaw"])}, {number(look["pitch"])})\n'
        if model.get('emissive'):
            glow = model['emissive']
            index += f'            .emissive({quoted(glow["texture"])}, {number(glow["idle"])}, {number(glow["pulse"])}, {number(glow["attack"])})\n'
        for glow in model.get('emissive_layers', []):
            index += f'            .emissive({quoted(glow["texture"])}, {number(glow["idle"])}, {number(glow["pulse"])}, {number(glow["attack"])})\n'
        for overlay in model.get('overlays', []):
            index += f'            .overlay({quoted(overlay["texture"])}, {str(overlay.get("full_bright", False)).lower()})\n'
        for overlay in model.get('animated_overlays', []):
            index += f'            .animatedOverlay({quoted(overlay["prefix"])}, {int(overlay["frames"])}, {int(overlay.get("ticks_per_frame", 1))}, {number(overlay.get("alpha", 1))}, {str(overlay.get("full_bright", True)).lower()})\n'
        if model.get('hidden_bones'):
            index += '            .hiddenBones(' + ', '.join(quoted(b) for b in model['hidden_bones']) + ')\n'
        if model.get('hand_items'):
            hands = model['hand_items']
            index += '            .handItems(' + (quoted(hands['right']) if hands.get('right') else 'null') + ', ' + (quoted(hands['left']) if hands.get('left') else 'null') + ', ' + str(hands.get('palm_anchor', False)).lower() + ')\n'
        if model.get('humanoid_gait'):
            gait = model['humanoid_gait']
            index += '            .humanoidGait(' + ', '.join(quoted(b) for b in gait['bones']) + ', ' + number(gait['speed']) + ', ' + number(gait['amplitude']) + ')\n'
        if model.get('cem_driver'):
            index += f'            .cemDriver({quoted(model["cem_driver"])})\n'
        for alias, node in model.get('host_aliases', {}).items():
            index += f'            .hostAlias({quoted(alias)}, {quoted(node)})\n'
        for binding in model.get('expressions', []):
            index += f'            .expression({quoted(binding["target"])}, {quoted(binding["expression"])})\n'
        for motion in model.get('bone_motions', []):
            if motion['kind'] == 'spin':
                index += f'            .spin({quoted(motion["bone"])}, {quoted(motion["axis"])}, {number(motion["speed"])})\n'
            else:
                index += f'            .oscillate({quoted(motion["bone"])}, {quoted(motion["axis"])}, {number(motion["amplitude"])}, {number(motion["speed"])}, {number(motion.get("phase", 0))})\n'
        index += '            .build());\n'
    index += '        return Map.copyOf(models);\n    }\n}\n'
    write_java('ReferenceModelIndex', index)
    print(f'Generated {len(generated)} geometry adapters, {len(imported)} animation libraries and {len(manifest["models"])} explicit model bindings.')


if __name__ == '__main__':
    main()
